"""Build the paper's worked example (Fig. 1) from the committed data.

One Study 1 item on the nano tier: the PURE source, the messified input the model saw, both annotators'
admissible patterns, and the outputs of the base prompt (F_base) and of the base prompt with examples (F_E).
Every value is read from the repository and checked; nothing is typed by hand.
Writes paper/sections/fig_example.tex. Run from the repository root.
"""
import json

import pandas as pd

ITEM = "PURE-053"
COLS = ["adm_ubiquitous", "adm_event_driven", "adm_unwanted_behaviour", "adm_state_driven",
        "adm_optional_feature", "adm_complex"]


def tex(s):
    for a, b in [("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"),
                 ("_", "\\_"), ("{", "\\{"), ("}", "\\}"), ("’", "'"), ("—", "---")]:
        s = s.replace(a, b)
    return s


def main():
    sheets = [pd.read_csv(f"study2b/pattern_fit/02_sheet_annotator_{x}.csv").set_index("item_id") for x in "AB"]
    for s in sheets:
        assert s.loc[ITEM, COLS].tolist() == [1, 0, 0, 0, 0, 0], "both annotators: only Ubiquitous admissible"
    pure = {d["id"]: d["text"] for d in json.load(open("data/pure_150.json", encoding="utf-8"))}
    mess = {d["id"]: d["messified_text"] for d in json.load(open("data/pure_150_messified.json", encoding="utf-8"))}
    rows = [json.loads(line) for line in open("study2/results/checks_study2.jsonl", encoding="utf-8")]
    out = {}
    for r in rows:
        if r["item_id"] == ITEM and r["model_id"] == "gpt-5.4-nano-2026-03-17" and r["arm"] in ("F_base", "F_E"):
            assert r["arm"] not in out
            out[r["arm"]] = r
    base, ex = out["F_base"], out["F_E"]
    assert base["ears_v2_compliant"] and base["pattern_v2"] == "optional-feature"
    assert ex["ears_v2_compliant"] and ex["pattern_v2"] == "ubiquitous"
    assert base["requirement_text"].startswith("WHERE ")

    L = ["% Generated by study2b/scripts/make_paper_example.py from the committed data.",
         "% Do not edit by hand: change the script and re-run it.",
         "\\begin{figure}",
         "  \\footnotesize",
         "  \\renewcommand{\\arraystretch}{1.15}",
         "  \\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{0.25\\linewidth}p{0.71\\linewidth}@{}}",
         "    \\toprule",
         f"    PURE source & {tex(pure[ITEM])} \\\\",
         f"    Input (what the model sees) & \\emph{{``{tex(mess[ITEM])}''}} \\\\",
         "    Admissible & Ubiquitous only (both annotators) \\\\",
         "    \\midrule",
         f"    Base prompt & {tex(base['requirement_text'])}\\newline \\textbf{{Checker: compliant. Pattern fit: no.}} \\\\",
         f"    Base prompt with examples & {tex(ex['requirement_text'])}\\newline \\textbf{{Checker: compliant. Pattern fit: yes.}} \\\\",
         "    \\bottomrule",
         "  \\end{tabular}",
         # Short caption; the explanation is in the Introduction, where the figure is cited.
         "  \\caption{Comparison of the EARS patterns chosen for one input under two prompts.}",
         "  \\Description{A table for one input. It gives the PURE source requirement, the informal input the "
         "model saw, and the admissible pattern (Ubiquitous only). It then shows two outputs: with the base prompt, "
         "a requirement opening with a WHERE clause, which passes the checker but does not fit; with worked "
         "examples, an unconditional requirement, which passes the checker and fits.}",
         "  \\label{fig:example}",
         "\\end{figure}", ""]
    with open("paper/sections/fig_example.tex", "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("Wrote paper/sections/fig_example.tex")


if __name__ == "__main__":
    main()
